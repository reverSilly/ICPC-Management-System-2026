<#
.SYNOPSIS
    合并 src 目录下的源代码，生成单文件 build/main.cpp。

.DESCRIPTION
    按固定顺序拼接 src 下的全部 .h/.hpp/.cpp 文件：头文件在前、源文件在后，
    同类文件按文件名排序，保证结果稳定可复现。
    拼接时去掉本地 #include "..." 行（合并后不再需要），保留系统头文件 <...>。
    生成结果用于 Online Judge 的单文件提交。

.PARAMETER SourceDir
    源代码目录，默认 <项目根>/src。

.PARAMETER OutFile
    输出文件，默认 <项目根>/build/main.cpp。
#>
[CmdletBinding()]
param(
    [string]$SourceDir,
    [string]$OutFile
)

$ErrorActionPreference = 'Stop'

$root = $PSScriptRoot
if (-not $SourceDir) { $SourceDir = Join-Path $root 'src' }
if (-not $OutFile)   { $OutFile   = Join-Path (Join-Path $root 'build') 'main.cpp' }

if (-not (Test-Path -LiteralPath $SourceDir -PathType Container)) {
    throw "merge: 找不到源目录 $SourceDir"
}

$allFiles = Get-ChildItem -LiteralPath $SourceDir -Recurse -File
$headers  = @($allFiles | Where-Object { $_.Extension -in @('.h', '.hpp') } | Sort-Object FullName)
$sources  = @($allFiles | Where-Object { $_.Extension -eq '.cpp' } | Sort-Object FullName)
$ordered  = @($headers) + @($sources)

if ($ordered.Count -eq 0) {
    throw "merge: $SourceDir 下没有可合并的文件 (*.h / *.hpp / *.cpp)"
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('// Auto-generated by merge.ps1. Do not edit by hand.')
[void]$sb.AppendLine('// Merged sources: ' + (($ordered | ForEach-Object { $_.Name }) -join ', '))
[void]$sb.AppendLine()

foreach ($file in $ordered) {
    $text = [System.IO.File]::ReadAllText($file.FullName)
    # 去掉本地 #include "..." 行，保留系统头文件 <...>
    $text = [regex]::Replace($text, '(?m)^[ \t]*#\s*include\s*"[^"]*"[ \t]*\r?\n?', '')
    # 合并为单文件后 #pragma once 已无意义，去掉以免 g++ 报 "pragma once in main file"
    $text = [regex]::Replace($text, '(?m)^[ \t]*#\s*pragma\s+once[ \t]*\r?\n?', '')
    $text = $text.TrimEnd()

    [void]$sb.AppendLine('// ===== ' + $file.Name + ' =====')
    [void]$sb.AppendLine($text)
    [void]$sb.AppendLine()
}

$outDir = Split-Path -Parent $OutFile
if ($outDir -and -not (Test-Path -LiteralPath $outDir)) {
    New-Item -ItemType Directory -Path $outDir -Force | Out-Null
}

# 以 UTF-8 无 BOM 写出，避免 g++ 因 BOM 报错
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($OutFile, $sb.ToString(), $utf8NoBom)

Write-Host ('[merge] merged {0} file(s) -> {1}' -f $ordered.Count, $OutFile)
