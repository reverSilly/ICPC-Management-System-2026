#!/usr/bin/env bash
#
# merge.sh - 合并 src 目录下的源代码，生成单文件 build/main.cpp。
#   头文件在前、源文件在后，同类按文件名排序；
#   去掉本地 #include "..." 行与 #pragma once，保留系统头文件 <...>。
#
# 用法: merge.sh [source_dir] [out_file]
#   默认 source_dir=<脚本目录>/src，out_file=<脚本目录>/build/main.cpp

set -euo pipefail
export LC_ALL=C

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC_DIR="${1:-$SCRIPT_DIR/src}"
OUT_FILE="${2:-$SCRIPT_DIR/build/main.cpp}"

if [ ! -d "$SRC_DIR" ]; then
    echo "merge: 找不到源目录 $SRC_DIR" >&2
    exit 1
fi

headers=()
while IFS= read -r f; do headers+=("$f"); done \
    < <(find "$SRC_DIR" -type f \( -name '*.h' -o -name '*.hpp' \) | sort)
sources=()
while IFS= read -r f; do sources+=("$f"); done \
    < <(find "$SRC_DIR" -type f -name '*.cpp' | sort)

total=$(( ${#headers[@]} + ${#sources[@]} ))
if [ "$total" -eq 0 ]; then
    echo "merge: $SRC_DIR 下没有可合并的文件 (*.h / *.hpp / *.cpp)" >&2
    exit 1
fi

names=""
for f in "${headers[@]}" "${sources[@]}"; do
    names="${names:+$names, }$(basename "$f")"
done

mkdir -p "$(dirname "$OUT_FILE")"

tmp="$OUT_FILE.tmp.$$"
{
    echo "// Auto-generated by merge.sh. Do not edit by hand."
    echo "// Merged sources: $names"
    echo
    for f in "${headers[@]}" "${sources[@]}"; do
        echo "// ===== $(basename "$f") ====="
        sed -E \
            -e '/^[[:space:]]*#[[:space:]]*include[[:space:]]*"/d' \
            -e '/^[[:space:]]*#[[:space:]]*pragma[[:space:]]+once[[:space:]]*$/d' \
            "$f"
        echo
    done
} > "$tmp"
mv "$tmp" "$OUT_FILE"

echo "[merge] merged $total file(s) -> $OUT_FILE"
